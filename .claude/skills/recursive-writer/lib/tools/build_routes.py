"""Build routes.md, the routing table, from each file's **Applies when:** line.

Every file in checks/ and reference/ with an Applies-when line is routed. Files with the same
trigger text share a row; "always." files are listed in the always-on line. Every other file needs a
**Triggers:** regex or a **Flags:** line, or load.sh --text can't route it; the build fails if one is
missing or a regex doesn't compile. Run after editing any Applies-when, Triggers, or Flags line.
"""
import glob, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from paths import LIB as D  # noqa: E402

rows, always, unrouted = {}, [], []
for f in sorted(glob.glob(f"{D}/checks/*.md") + glob.glob(f"{D}/reference/*.md")):
    src = open(f).read()
    m = re.search(r"^\*\*Applies when:\*\* (.+)$", src, re.M)
    if not m:
        continue
    fid = os.path.basename(f)[:-3]
    short = fid.split("-")[0] if re.match(r"^\d\d-", fid) or re.match(r"^L\d-", fid) else fid
    if m.group(1).strip() == "always.":
        always.append(short)
    else:
        rows.setdefault(m.group(1).strip().rstrip("."), []).append(short)
        t = re.search(r"^\*\*Triggers:\*\* (.+)$", src, re.M)
        if t:
            re.compile(t.group(1).strip(), re.I | re.M)  # a bad regex fails here, not mid-review
        if not t and not re.search(r"^\*\*Flags:\*\* ", src, re.M):
            unrouted.append(fid)
if unrouted:
    raise SystemExit("No **Triggers:** or **Flags:** line, so load.sh --text never loads: " + ", ".join(unrouted))
table = ["Always on: " + " ".join(f"`{a}`" for a in always) + ".", "",
         "| The wording has | Add |", "|---|---|"]
table += [f"| {k} | `{' '.join(v)}` |" for k, v in rows.items()]
header = ["# Routes", "",
          "Generated by tools/build_routes.py from each file's **Applies when:** line. Don't edit by hand.",
          ""]
open(f"{D}/routes.md", "w").write("\n".join(header + table) + "\n")
print(f"{len(always)} always-on, {len(rows)} trigger rows")
